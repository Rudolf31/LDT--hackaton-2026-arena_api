// Package ai — клиенты двух моделей авторства сценария: расшифровка
// надиктованного описания (Transcriber, ARENA_STT_*) и документ сценария
// целиком по описанию или по указанию на правку (ScenarioGenerator,
// ARENA_GEN_*). Обе — arena-portal-backend-architecture.md 10.2, D-13, D-32.
//
// Ни в каком другом месте портала к моделям не ходят: в цикле разговора
// клиент-тренажёр вызывает их сам (CLAUDE.md, «Авторство сценария»).
// Пакет не импортирует internal/modules/* — модуль generation собирает
// клиентов в cmd/portal/main.go и передаёт их сюда снаружи как интерфейсы.
package ai

import (
	"context"
	"errors"
	"io"
)

// Transcriber — расшифровка mp3 в текст. audio читается целиком в память
// вызывающей стороной не является — реализация сама решает, сколько
// буферизовать; мы читаем io.Reader потоково и нигде не сохраняем сам
// звук (I-11).
type Transcriber interface {
	Transcribe(ctx context.Context, audio io.Reader) (string, error)
}

// ScenarioGenerator — документ сценария arena-scenario/1 целиком.
// base == nil — создание с нуля по brief; base != nil — правка: brief
// тогда несёт указание, что изменить, а base — текущий документ.
// problems — диагностика прошлой попытки текстом («путь: сообщение»),
// пусто на первом вызове (D-33).
type ScenarioGenerator interface {
	Generate(ctx context.Context, brief string, base []byte, problems []string) ([]byte, error)
}

// Доменные ошибки моделей — короткая русская фраза без подробностей
// ответа провайдера: там может быть текст надиктованного описания или
// реплики, которые нельзя ни разу показать пользователю как есть и нельзя
// логировать (CLAUDE.md, правило 5). Вызывающая сторона (generation)
// собирает из них полный экранный текст с контекстом попытки.
var (
	// ErrNotConfigured — клиент собран без ключа или модели. Практически не
	// возникает: cmd/portal/main.go передаёт в generation.New(nil, nil, …)
	// вместо клиента, когда cfg.GenConfigured()/STTConfigured() говорит
	// «нет» (D-34/D-35) — сам пакет ai до вызова модели не доходит. Ошибка
	// остаётся как защита на случай, если клиента всё же собрали с пустыми
	// значениями.
	ErrNotConfigured = errors.New("модель не настроена")
	// ErrTimeout — модель не ответила в срок вызова (генерация — 180 с,
	// расшифровка — 90 с; таймауты выставляет generation/service.go).
	ErrTimeout = errors.New("модель не ответила вовремя")
	// ErrUpstream — модель ответила ошибкой или не тем, что нужно
	// (не JSON, пустой ответ). Текст самого ответа провайдера в err не
	// попадает — только код состояния, если он был.
	ErrUpstream = errors.New("модель ответила ошибкой")
)
